CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (length(trim(nome)) > 0),
    telefone VARCHAR(30), email VARCHAR(150), ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id),
    profissional VARCHAR(100) NOT NULL CHECK (length(trim(profissional)) > 0),
    observacoes VARCHAR(2000) NOT NULL CHECK (length(trim(observacoes)) > 0),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX atendimento_cliente_idx ON atendimento(cliente_id);
CREATE TABLE receita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id),
    prescritor VARCHAR(100) NOT NULL CHECK (length(trim(prescritor)) > 0),
    numero VARCHAR(80) NOT NULL CHECK (length(trim(numero)) > 0),
    emitida_em DATE NOT NULL, validade_ate DATE NOT NULL,
    observacoes VARCHAR(2000), CHECK (validade_ate >= emitida_em)
);
CREATE INDEX receita_cliente_idx ON receita(cliente_id);
CREATE TABLE item_receita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receita_id BIGINT NOT NULL REFERENCES receita(id),
    medicamento_id BIGINT NOT NULL REFERENCES medicamento(id),
    quantidade INTEGER NOT NULL CHECK (quantidade BETWEEN 1 AND 9999),
    UNIQUE (receita_id, medicamento_id)
);
CREATE TABLE dispensacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receita_id BIGINT NOT NULL REFERENCES receita(id),
    venda_id BIGINT NOT NULL UNIQUE REFERENCES venda(id),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX dispensacao_receita_idx ON dispensacao(receita_id);
CREATE TABLE configuracao (
    id BIGINT PRIMARY KEY CHECK (id=1),
    nome_farmacia VARCHAR(100) NOT NULL CHECK (length(trim(nome_farmacia)) > 0),
    telefone VARCHAR(30), email VARCHAR(150), endereco VARCHAR(200)
);
